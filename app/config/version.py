# 01.03  (2026-11-23) 끌어 고른 글자 영역이 안 보이던 것 - 반투명 검정 선택색이 다크 모드 팔레트와 섞였다 → 불투명 Windows 파랑
#        (#0078D7 + 흰 글자, 바탕이 비슷한 파랑이면 주황), 포커스 없는 창에서도. 목록 창 Push Shared 버튼 = 공유 노트(shared/notes)만
#        커밋 · 푸시(다른 파일 · 이 PC 노트 제외, 안 올라간 다른 커밋이 있으면 멈춤, 다른 PC 가 먼저 올렸으면 pull --rebase 후 다시).

# 01.04  (2026-11-23) 목록 창 Shrink (A00220_BackupTool 과 같은 방식) - 272 x 155 로 줄이고 아이콘 애니메이션 · Shrunk · Pin 만 남긴다
#        (Pin 은 Shrunk 아래). 애니메이션 = 색 스티커가 떨어져 → 연필이 세 줄 쓰고 → 압정 → 날아가고 다음 색, 끝없이 반복
#        (줄여 둔 동안만 타이머). 애니메이션 클릭 = 펴기, 줄인 채 끄면 줄인 채로 켜지고 펼 때 원래 크기.

# 01.05  (2026-11-23) 글자 크기 - 노트마다 A- / 100% / A+ · Ctrl + 휠 · Ctrl+= / - / 0 (60~300%, 이 PC state.json 에 기억 - 공유 파일 불변),
#        목록 창 카드 글자 Ctrl + 휠 · 메뉴. 저장 HTML 의 body font-size(11pt 고정)를 빼서 크기가 따라오게(옛 노트도).
#        QFont(이름, 소수) 가 크기를 정수로 자르던 것. Shrunk 버튼은 켜져도 연한 빨강이 아니게(사용자).

# 01.06  (2026-11-23) 고른 글자만 크기 - 노트 아래 T- / T+ (Ctrl+Shift+, / .), 상대 단계(작게 ~ 가장 크게)라 노트 전체 배율과 곱해진다.
#        섞인 크기는 조각마다 한 단계, Ctrl+Z 한 번, 고른 것 없으면 이어서 칠 글자. 노트 전체 배율(A- / A+)은 그대로.
#        목록 창 Shrink · Pin 을 배경과 구분되는 버튼으로(바탕 + 테두리, Shrunk 는 굵은 테두리 - 빨강 아님). 아래 줄 여백을 줄여 100% 가 잘리지 않게.

# 01.07  (2026-11-23) Shared / This PC 를 색으로 구분 - 노트 위쪽 · 목록 카드의 배지를 꽉 찬 범위 색(Shared 파랑 #1A73E8,
#        This PC 초록 #2E7D32, 흰 글자)으로, 목록 카드 왼쪽에 같은 색 띠. Push Shared 버튼 테두리가 안 보이던 것(선택자 구체성).

# 01.08  (2026-11-23) 새 노트의 기본 색 = 저장된 노트 색(마지막으로 고른 색, state.json note_color - 옛 파일이면 가장 최근에 고친
